  # 表の番地は __fpga_uni_case_data の irep の pool から読む (literal の順: 0 pool、1 lower_runs、2 lower_multi、3 upper_runs、
  # 4 upper_multi、5 title_runs、6 title_multi、7 swap_multi、8 fold_runs、9 fold_multi。SWAP の runs は NULL)
  # C: src/unicase.c case_tables
  def __fpga_case_table(kind)
    pr = __fpga_and(__fpga_search(__fpga_image(5), __fpga_addr(:__fpga_uni_case_data)), -4) # L:IMG_object_class 可視性の bit を除く
    pool = __fpga_ld32(__fpga_ld32(pr + 8) + 12) # L:P_BODY L:I_POOL
    if kind == 0
      r = 1
      m = 2
      min = 192 # UNI_LOWER_MIN 0x000C0
      max = 125217 # UNI_LOWER_MAX 0x1E921
    elsif kind == 1
      r = 3
      m = 4
      min = 181 # UNI_UPPER_MIN 0x000B5
      max = 125251 # UNI_UPPER_MAX 0x1E943
    elsif kind == 2
      r = 5
      m = 6
      min = 223 # UNI_TITLE_MIN 0x000DF
      max = 64279 # UNI_TITLE_MAX 0x0FB17
    elsif kind == 3
      r = -1 # UNI_SWAP_RUNS NULL
      m = 7
      min = 453 # UNI_SWAP_MIN 0x001C5
      max = 8188 # UNI_SWAP_MAX 0x01FFC
    else
      r = 8
      m = 9
      min = 181 # UNI_FOLD_MIN 0x000B5
      max = 64279 # UNI_FOLD_MAX 0x0FB17
    end
    runs = r < 0 ? 0 : __fpga_ldv(pool + r * 16) # L:VALUE
    multi = __fpga_ldv(pool + m * 16) # L:VALUE
    [r < 0 ? 0 : __fpga_lo(runs), r < 0 ? 0 : __fpga_hi(runs) / 6, __fpga_lo(multi), __fpga_hi(multi) / 5, min, max] # UNI_CASE_RUN_BYTES UNI_CASE_MULTI_BYTES
  end

  # uni_case_pool の番地
  # C: src/unicase.h uni_case_pool
  def __fpga_uni_case_pool
    pr = __fpga_and(__fpga_search(__fpga_image(5), __fpga_addr(:__fpga_uni_case_data)), -4) # L:IMG_object_class 可視性の bit を除く
    __fpga_lo(__fpga_ldv(__fpga_ld32(__fpga_ld32(pr + 8) + 12))) # L:P_BODY L:I_POOL
  end

  # p から n バイト、下の桁から
  # C: src/unicase.c case_bits
  def __fpga_case_bits(p, n)
    v = 0
    i = 0
    while i < n
      v = __fpga_or(v, __fpga_shl(__fpga_ld8(p + i), 8 * i))
      i += 1
    end
    v
  end

  # [start, count, stride, delta]
  # C: src/unicase.c case_run_at
  def __fpga_case_run_at(runs, i)
    v = __fpga_case_bits(runs + i * 6, 6) # UNI_CASE_RUN_BYTES
    [__fpga_and(v, 2097151), __fpga_and(__fpga_shr(v, 21), 127), __fpga_and(__fpga_shr(v, 28), 1) + 1,
     __fpga_and(__fpga_shr(v, 29), 131071) - 65536] # 0x1FFFFF 0x7F 0x1FFFF UNI_CASE_DELTA_BIAS
  end

  # cp を持つ run (無ければ nil)
  # C: src/unicase.c case_run_for
  def __fpga_case_run_for(t, cp)
    runs = __fpga_aref(t, 0)
    lo = 0
    hi = __fpga_aref(t, 1)
    while lo < hi
      mid = lo + __fpga_shr(hi - lo, 1)
      r = __fpga_case_run_at(runs, mid)
      start = __fpga_aref(r, 0)
      last = start + (__fpga_aref(r, 1) - 1) * __fpga_aref(r, 2)
      if cp < start
        hi = mid
      elsif cp > last
        lo = mid + 1
      else
        return nil unless __fpga_and(cp - start, __fpga_aref(r, 2) - 1) == 0 # (cp - r.start) % r.stride (stride は 1 か 2)
        return r
      end
    end
    nil
  end

  # [off, len] (無ければ nil)
  # C: src/unicase.c case_multi_for
  def __fpga_case_multi_for(t, cp)
    multi = __fpga_aref(t, 2)
    lo = 0
    hi = __fpga_aref(t, 3)
    while lo < hi
      mid = lo + __fpga_shr(hi - lo, 1)
      v = __fpga_case_bits(multi + mid * 5, 5) # UNI_CASE_MULTI_BYTES
      mcp = __fpga_and(v, 2097151) # 0x1FFFFF
      if cp < mcp
        hi = mid
      elsif cp > mcp
        lo = mid + 1
      else
        return [__fpga_and(__fpga_shr(v, 21), 4095), __fpga_and(__fpga_shr(v, 33), 7)] # 0xFFF
      end
    end
    nil
  end

  # 書いたバイトの数。0 はその表が自分へ写す文字、-1 は表が何も言わない文字
  # C: src/unicase.c case_map_one
  def __fpga_case_map_one(kind, cp, buf)
    t = __fpga_case_table(kind)
    return -1 if cp < __fpga_aref(t, 4) || __fpga_aref(t, 5) < cp
    m = __fpga_case_multi_for(t, cp)
    if m
      __fpga_copy(buf, __fpga_uni_case_pool + __fpga_aref(m, 0), __fpga_aref(m, 1))
      return __fpga_aref(m, 1)
    end
    r = __fpga_case_run_for(t, cp)
    return -1 unless r
    return 0 if __fpga_aref(r, 3) == 0
    __fpga_utf8_to_buf(buf, cp + __fpga_aref(r, 3))
  end

  # C: src/unicase.c mrb_uni_case_map
  def __fpga_uni_case_map(kind, cp, buf)
    n = __fpga_case_map_one(kind, cp, buf)
    return n if n >= 0
    if kind == 2 # MRB_CASE_KIND_TITLE
      n = __fpga_case_map_one(1, cp, buf) # MRB_CASE_KIND_UPPER
    elsif kind == 3 # MRB_CASE_KIND_SWAP
      n = __fpga_case_map_one(0, cp, buf) # MRB_CASE_KIND_LOWER
      n = __fpga_case_map_one(1, cp, buf) if n < 0
    elsif kind == 4 # MRB_CASE_KIND_FOLD
      n = __fpga_case_map_one(0, cp, buf)
    end
    n < 0 ? 0 : n
  end

