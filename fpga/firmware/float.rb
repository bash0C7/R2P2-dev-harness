# firmware: Float (mruby の src/numeric.c の Float の所、src/fp_uscale.c の数と文字列の変換)。
# コアに浮動小数点の演算器は無い。double の演算 (C はハードウェアの double) は、下の soft-float の helper が
# 整数の演算で IEEE 754 binary64 と同じ結果 (最近接の偶数への丸め、非正規化数、無限大、NaN、符号付きの 0) を出す (D50)。
# helper は double のビットの並び (64bit の2の補数の Integer) を受けて返す。値は {TAG_FLOAT, ビット} (D01)。
class Object
  # --- soft-float の芯 (D50)。C は double の演算子 (+ - * /)、比べる演算子、(double) と (mrb_int) の型の変換

  # 桁の長さ (C の 64 - clz64、fp_uscale.c の bits_len64)。m >= 0
  # C: none (D50)
  def __fpga_bitlen(m)
    n = 0
    if m >= 4294967296
      m = __fpga_shr(m, 32)
      n += 32
    end
    if m >= 65536
      m = __fpga_shr(m, 16)
      n += 16
    end
    if m >= 256
      m = __fpga_shr(m, 8)
      n += 8
    end
    if m >= 16
      m = __fpga_shr(m, 4)
      n += 4
    end
    if m >= 4
      m = __fpga_shr(m, 2)
      n += 2
    end
    if m >= 2
      m = __fpga_shr(m, 1)
      n += 1
    end
    n + m
  end

  # 値 m * 2^e (m は 0〜2^63-1) を、最近接の偶数へ丸めて double のビットにする。neg は符号。
  # m の bit 0 は、捨てた桁が 0 でない印 (sticky) を or したものでもよい。その時 m は 55bit 以上 (丸めの位置が 2 桁以上上)
  # C: none (D50)
  def __fpga_f64_pack(neg, e, m)
    sign = neg ? -9223372036854775807 - 1 : 0
    return sign if m == 0
    n = __fpga_bitlen(m)
    l = e + n - 53 # 結果の一番下の桁の重み (2^l)
    l = -1074 if l < -1074 # 非正規化数
    s = l - e
    if s <= 0
      sig = __fpga_shl(m, 0 - s)
    else
      return sign if s >= 64 # m < 2^63 は半分 2^(s-1) より小さい
      if s == 63 # 半分は 2^62。より大きければ一番小さい非正規化数へ上げる
        return sign if m <= 4611686018427387904
        return __fpga_or(sign, 1)
      end
      sig = __fpga_shr(m, s)
      rem = __fpga_and(m, __fpga_shl(1, s) - 1)
      half = __fpga_shl(1, s - 1)
      if rem > half || (rem == half && __fpga_and(sig, 1) == 1)
        sig += 1
        if sig == 9007199254740992 # 2^53
          sig = 4503599627370496 # 2^52
          l += 1
        end
      end
    end
    return __fpga_or(sign, sig) if sig < 4503599627370496 # 非正規化数 (指数の欄は 0)
    biased = l + 1075
    return __fpga_or(sign, 9218868437227405312) if biased >= 2047 # 無限大
    __fpga_or(sign, __fpga_or(__fpga_shl(biased, 52), sig - 4503599627370496))
  end

  # NaN を含む 2 つの演算: x86 の SSE と同じく、左が NaN なら左を、でなければ右を quiet にして返す
  # C: none (D50)
  def __fpga_f64_nan2(a, b)
    return __fpga_or(a, 2251799813685248) if __fpga_and(a, 9223372036854775807) > 9218868437227405312
    __fpga_or(b, 2251799813685248)
  end

  # a + b
  # C: none (D50)
  def __fpga_f64_add(a, b)
    xa = __fpga_and(a, 9223372036854775807)
    xb = __fpga_and(b, 9223372036854775807)
    return __fpga_f64_nan2(a, b) if xa > 9218868437227405312 || xb > 9218868437227405312
    if xa == 9218868437227405312
      return -2251799813685248 if xb == 9218868437227405312 && ((a < 0) == (b < 0)) == false # 無限大 - 無限大は既定の NaN
      return a
    end
    return b if xb == 9218868437227405312
    if xa == 0
      return __fpga_and(a, b) if xb == 0 # 0 + 0 は、両方 -0 の時だけ -0
      return b
    end
    return a if xb == 0
    neg = a < 0
    negb = b < 0
    ea = __fpga_shr(xa, 52)
    ma = __fpga_and(xa, 4503599627370495)
    if ea == 0
      ea = 1
    else
      ma += 4503599627370496
    end
    eb = __fpga_shr(xb, 52)
    mb = __fpga_and(xb, 4503599627370495)
    if eb == 0
      eb = 1
    else
      mb += 4503599627370496
    end
    if ea < eb # 指数の大きい方を a に
      t = ea
      ea = eb
      eb = t
      t = ma
      ma = mb
      mb = t
      t = neg
      neg = negb
      negb = t
    end
    ma = __fpga_shl(ma, 9) # 9 桁の余裕 (62bit まで)
    mb = __fpga_shl(mb, 9)
    d = ea - eb
    if d >= 62
      mb = 1
    elsif d > 0
      lost = __fpga_and(mb, __fpga_shl(1, d) - 1)
      mb = __fpga_shr(mb, d)
      mb = __fpga_or(mb, 1) if lost > 0
    end
    if neg == negb
      m = ma + mb
    else
      m = ma - mb
      if m < 0
        m = 0 - m
        neg = negb
      end
      return 0 if m == 0 # 最近接の丸めでは x - x は +0
    end
    __fpga_f64_pack(neg, ea - 1084, m) # 1075 + 9
  end

  # a - b
  # C: none (D50)
  def __fpga_f64_sub(a, b)
    return __fpga_f64_nan2(a, b) if __fpga_and(a, 9223372036854775807) > 9218868437227405312 || __fpga_and(b, 9223372036854775807) > 9218868437227405312
    __fpga_f64_add(a, __fpga_xor(b, -9223372036854775807 - 1))
  end

  # a * b。仮数の積 (106bit まで) を 2^54 進の 2 桁で作る
  # C: none (D50)
  def __fpga_f64_mul(a, b)
    xa = __fpga_and(a, 9223372036854775807)
    xb = __fpga_and(b, 9223372036854775807)
    return __fpga_f64_nan2(a, b) if xa > 9218868437227405312 || xb > 9218868437227405312
    neg = ((a < 0) == (b < 0)) == false
    sign = neg ? -9223372036854775807 - 1 : 0
    if xa == 9218868437227405312 || xb == 9218868437227405312
      return -2251799813685248 if xa == 0 || xb == 0 # 無限大 * 0 は既定の NaN
      return __fpga_or(sign, 9218868437227405312)
    end
    return sign if xa == 0 || xb == 0
    ea = __fpga_shr(xa, 52)
    ma = __fpga_and(xa, 4503599627370495)
    if ea == 0
      ea = 1
    else
      ma += 4503599627370496
    end
    eb = __fpga_shr(xb, 52)
    mb = __fpga_and(xb, 4503599627370495)
    if eb == 0
      eb = 1
    else
      mb += 4503599627370496
    end
    ah = __fpga_shr(ma, 27)
    al = __fpga_and(ma, 134217727)
    bh = __fpga_shr(mb, 27)
    bl = __fpga_and(mb, 134217727)
    mid = ah * bl + al * bh
    lo = al * bl + __fpga_shl(__fpga_and(mid, 134217727), 27)
    hi = ah * bh + __fpga_shr(mid, 27) + __fpga_shr(lo, 54)
    lo = __fpga_and(lo, 18014398509481983) # 2^54 - 1
    e = ea + eb - 2150
    return __fpga_f64_pack(neg, e, lo) if hi == 0
    t = __fpga_bitlen(hi) + 54 - 62
    return __fpga_f64_pack(neg, e, __fpga_or(__fpga_shl(hi, 54), lo)) if t <= 0
    m = __fpga_or(__fpga_shl(hi, 54 - t), __fpga_shr(lo, t))
    m = __fpga_or(m, 1) if __fpga_and(lo, __fpga_shl(1, t) - 1) > 0
    __fpga_f64_pack(neg, e + t, m)
  end

  # a / b。仮数の商を 10bit ずつの割り算で 60bit まで
  # C: none (D50)
  def __fpga_f64_div(a, b)
    xa = __fpga_and(a, 9223372036854775807)
    xb = __fpga_and(b, 9223372036854775807)
    return __fpga_f64_nan2(a, b) if xa > 9218868437227405312 || xb > 9218868437227405312
    neg = ((a < 0) == (b < 0)) == false
    sign = neg ? -9223372036854775807 - 1 : 0
    if xa == 9218868437227405312
      return -2251799813685248 if xb == 9218868437227405312 # 無限大 / 無限大
      return __fpga_or(sign, 9218868437227405312)
    end
    return sign if xb == 9218868437227405312
    if xb == 0
      return -2251799813685248 if xa == 0 # 0 / 0
      return __fpga_or(sign, 9218868437227405312)
    end
    return sign if xa == 0
    ea = __fpga_shr(xa, 52)
    ma = __fpga_and(xa, 4503599627370495)
    if ea == 0
      k = 53 - __fpga_bitlen(ma)
      ma = __fpga_shl(ma, k)
      ea = 1 - k
    else
      ma += 4503599627370496
    end
    eb = __fpga_shr(xb, 52)
    mb = __fpga_and(xb, 4503599627370495)
    if eb == 0
      k = 53 - __fpga_bitlen(mb)
      mb = __fpga_shl(mb, k)
      eb = 1 - k
    else
      mb += 4503599627370496
    end
    q = 0
    r = ma
    if r >= mb
      q = 1
      r -= mb
    end
    i = 0
    while i < 6
      r = __fpga_shl(r, 10)
      d = r / mb
      q = __fpga_shl(q, 10) + d
      r -= d * mb
      i += 1
    end
    q = __fpga_or(q, 1) if r > 0
    __fpga_f64_pack(neg, ea - eb - 60, q)
  end

  # (double)i (mrb_int から、最近接の偶数へ丸める)
  # C: none (D50)
  def __fpga_f64_from_int(i)
    return 0 if i == 0
    return -4332462841530417152 if i == -9223372036854775807 - 1 # -2^63
    return __fpga_f64_pack(true, 0, 0 - i) if i < 0
    __fpga_f64_pack(false, 0, i)
  end

  # (mrb_int)f (0 に向けて切る)。f は有限で mrb_int に入る (FIXABLE_FLOAT を呼ぶ側が調べる)
  # C: none (D50)
  def __fpga_f64_to_int(f)
    x = __fpga_and(f, 9223372036854775807)
    e = __fpga_shr(x, 52)
    return 0 if e < 1023
    m = __fpga_and(x, 4503599627370495) + 4503599627370496
    s = e - 1075
    v = s >= 0 ? __fpga_shl(m, s) : __fpga_shr(m, 0 - s)
    return v if v < 0 # -2^63
    f < 0 ? 0 - v : v
  end

  # 比べる (C の < == > を double で): -1、0、1、どちらかが NaN なら 2
  # C: none (D50)
  def __fpga_f64_cmp(a, b)
    xa = __fpga_and(a, 9223372036854775807)
    xb = __fpga_and(b, 9223372036854775807)
    return 2 if xa > 9218868437227405312 || xb > 9218868437227405312
    return 0 if xa == 0 && xb == 0 # 0.0 == -0.0
    ka = a < 0 ? 0 - xa : xa
    kb = b < 0 ? 0 - xb : xb
    return -1 if ka < kb
    return 1 if ka > kb
    0
  end

  # C の isnan
  # C: none (D50)
  def __fpga_f64_nan_p(a)
    __fpga_and(a, 9223372036854775807) > 9218868437227405312
  end

  # C の isinf
  # C: none (D50)
  def __fpga_f64_inf_p(a)
    __fpga_and(a, 9223372036854775807) == 9218868437227405312
  end

  # --- libc の関数 (D17)。どれも丸めの要らない (結果が double で正確な) 関数

  # floor
  # C: none (D17)
  def __fpga_f64_floor(a)
    x = __fpga_and(a, 9223372036854775807)
    e = __fpga_shr(x, 52) - 1023
    return a if e >= 52 # 整数か、無限大か NaN
    if e < 0
      return a if x == 0
      return a < 0 ? -4616189618054758400 : 0 # -1.0 か +0.0
    end
    mask = __fpga_shl(1, 52 - e) - 1
    return a if __fpga_and(x, mask) == 0
    r = __fpga_and(x, __fpga_xor(mask, -1))
    return r if a >= 0
    __fpga_or(r + mask + 1, -9223372036854775807 - 1) # 負は絶対値を 1 上げる (仮数の桁上げは指数へ続く)
  end

  # ceil
  # C: none (D17)
  def __fpga_f64_ceil(a)
    x = __fpga_and(a, 9223372036854775807)
    e = __fpga_shr(x, 52) - 1023
    return a if e >= 52
    if e < 0
      return a if x == 0
      return a < 0 ? -9223372036854775807 - 1 : 4607182418800017408 # -0.0 か 1.0
    end
    mask = __fpga_shl(1, 52 - e) - 1
    return a if __fpga_and(x, mask) == 0
    r = __fpga_and(x, __fpga_xor(mask, -1))
    return __fpga_or(r, -9223372036854775807 - 1) if a < 0
    r + mask + 1
  end

  # trunc
  # C: none (D17)
  def __fpga_f64_trunc(a)
    return __fpga_f64_ceil(a) if a < 0
    __fpga_f64_floor(a)
  end

  # round (0.5 は 0 から遠い方へ)
  # C: none (D17)
  def __fpga_f64_round(a)
    x = __fpga_and(a, 9223372036854775807)
    e = __fpga_shr(x, 52) - 1023
    return a if e >= 52
    sign = __fpga_and(a, -9223372036854775807 - 1)
    return sign if e < -1
    return __fpga_or(sign, 4607182418800017408) if e == -1 # 0.5 <= |a| < 1 は ±1.0
    mask = __fpga_shl(1, 52 - e) - 1
    r = x + __fpga_shl(1, 51 - e)
    __fpga_or(sign, __fpga_and(r, __fpga_xor(mask, -1)))
  end

  # fmod (a - b * trunc(a / b) を正確に)
  # C: none (D17)
  def __fpga_f64_fmod(a, b)
    xa = __fpga_and(a, 9223372036854775807)
    xb = __fpga_and(b, 9223372036854775807)
    return __fpga_f64_nan2(a, b) if xa > 9218868437227405312 || xb > 9218868437227405312
    return -2251799813685248 if xa == 9218868437227405312 || xb == 0
    return a if xb == 9218868437227405312 || xa < xb
    ea = __fpga_shr(xa, 52)
    ma = __fpga_and(xa, 4503599627370495)
    if ea == 0
      ea = 1
    else
      ma += 4503599627370496
    end
    eb = __fpga_shr(xb, 52)
    mb = __fpga_and(xb, 4503599627370495)
    if eb == 0
      eb = 1
    else
      mb += 4503599627370496
    end
    r = ma - (ma / mb) * mb
    d = ea - eb
    while d > 0
      k = d > 10 ? 10 : d
      r = __fpga_shl(r, k)
      r -= (r / mb) * mb
      d -= k
    end
    return __fpga_and(a, -9223372036854775807 - 1) if r == 0
    __fpga_f64_pack(a < 0, eb - 1075, r)
  end

  # pow (libc)。指数が整数の時は、仮数 128bit の途中の値で累乗 (2 乗と掛け算) し、最後に 1 回だけ丸める。
  # 負の指数は 1/x を 128bit で作って累乗する。指数が整数でない正の底は log と exp が要るので写していない (止まる)
  # C: none (D17)
  def __fpga_f64_pow(x, y)
    xa = __fpga_and(x, 9223372036854775807)
    ya = __fpga_and(y, 9223372036854775807)
    return 4607182418800017408 if ya == 0 # pow(x, ±0) は 1
    return 4607182418800017408 if x == 4607182418800017408 # pow(1, y) は 1
    return __fpga_f64_nan2(x, y) if xa > 9218868437227405312 || ya > 9218868437227405312
    if ya == 9218868437227405312
      return 4607182418800017408 if x == -4616189618054758400 # pow(-1, ±無限大) は 1
      c = __fpga_f64_cmp(xa, 4607182418800017408)
      return 4607182418800017408 if c == 0
      return (c < 0) == (y < 0) ? 9218868437227405312 : 0
    end
    yint = __fpga_f64_floor(y) == y
    yodd = yint && ya < 4845873199050653696 && __fpga_and(__fpga_f64_to_int(ya), 1) == 1 # |y| < 2^53 の奇数
    if xa == 0
      return yodd ? __fpga_or(__fpga_and(x, -9223372036854775807 - 1), 9218868437227405312) : 9218868437227405312 if y < 0
      return yodd ? x : 0
    end
    if xa == 9218868437227405312
      if x < 0
        return yodd ? -9223372036854775807 - 1 : 0 if y < 0
        return yodd ? __fpga_or(-9223372036854775807 - 1, 9218868437227405312) : 9218868437227405312
      end
      return y < 0 ? 0 : 9218868437227405312
    end
    unless yint
      return -2251799813685248 if x < 0 # 負の底と整数でない指数は NaN
      __fpga_halt # 整数でない指数 (log と exp) は写していない
    end
    neg = x < 0 && yodd
    sign = neg ? -9223372036854775807 - 1 : 0
    if ya >= 4890909195324358656 # |y| >= 2^63 (偶数): |x| と 1 の大小で無限大か 0 (|x| = 1 は 1)
      c = __fpga_f64_cmp(xa, 4607182418800017408)
      return 4607182418800017408 if c == 0
      return (c > 0) == (y > 0) ? 9218868437227405312 : 0
    end
    n = __fpga_f64_to_int(ya)
    ex = __fpga_shr(xa, 52)
    mx = __fpga_and(xa, 4503599627370495)
    if ex == 0
      k = 53 - __fpga_bitlen(mx)
      mx = __fpga_shl(mx, k)
      ex = 1 - k
    else
      mx += 4503599627370496
    end
    b = y < 0 ? __fpga_f128_recip(mx, ex) : [__fpga_shl(mx, 11), 0, ex - 1150, false] # 1075 + 11 + 64
    r = [-9223372036854775807 - 1, 0, -127, false] # 1 = 2^63 * 2^64 * 2^-127
    while n > 0
      r = __fpga_f128_mul(r, b) if __fpga_and(n, 1) == 1
      n = __fpga_shr(n, 1)
      if n > 0
        eb = __fpga_aref(b, 2)
        return __fpga_or(sign, 9218868437227405312) if eb > 1048576 # 残りの掛け算で必ずあふれる
        return sign if eb < -1048576 # 必ず 0 へ
        b = __fpga_f128_mul(b, b)
      end
    end
    rh = __fpga_aref(r, 0)
    m = __fpga_u64_shr(rh, 2)
    m = __fpga_or(m, 1) if __fpga_and(rh, 3) > 0 || (__fpga_aref(r, 1) == 0) == false || __fpga_aref(r, 3)
    __fpga_f64_pack(neg, __fpga_aref(r, 2) + 66, m)
  end

  # 128bit の仮数の積。x と y は [h, l, e, 不正確]、値は (h * 2^64 + l) * 2^e で h の最上位の bit が立つ。
  # 上の 128bit だけを残す (捨てた桁が 0 でなければ不正確の印)
  # C: none (D17)
  def __fpga_f128_mul(x, y)
    h1 = __fpga_aref(x, 0)
    l1 = __fpga_aref(x, 1)
    h2 = __fpga_aref(y, 0)
    l2 = __fpga_aref(y, 1)
    ah = __fpga_mul64(h1, h2, true)
    al = __fpga_mul64(h1, h2, false)
    b = __fpga_mul64(h1, l2, true)
    c = __fpga_mul64(l1, h2, true)
    inexact = __fpga_aref(x, 3) || __fpga_aref(y, 3) || (l1 == 0) == false || (l2 == 0) == false
    rl = __fpga_u64_add(al, b)
    carry = __fpga_u64_lt(rl, al) ? 1 : 0
    rl2 = __fpga_u64_add(rl, c)
    carry += 1 if __fpga_u64_lt(rl2, rl)
    rh = __fpga_u64_add(ah, carry)
    e = __fpga_aref(x, 2) + __fpga_aref(y, 2) + 128
    if rh >= 0 # 最上位の bit が立っていなければ 1 桁上げる
      rh = __fpga_or(__fpga_shl(rh, 1), __fpga_u64_shr(rl2, 63))
      rl2 = __fpga_shl(rl2, 1)
      e -= 1
    end
    [rh, rl2, e, inexact]
  end

  # 1 / (mx * 2^(ex - 1075)) を 128bit の仮数で (1 bit ずつの割り算)。mx は 53bit
  # C: none (D17)
  def __fpga_f128_recip(mx, ex)
    h = 0
    l = 0
    r = 1
    n = 0
    while h >= 0
      r = __fpga_shl(r, 1)
      bit = 0
      if r >= mx
        r -= mx
        bit = 1
      end
      h = __fpga_or(__fpga_shl(h, 1), __fpga_u64_shr(l, 63))
      l = __fpga_or(__fpga_shl(l, 1), bit)
      n += 1
    end
    [h, l, 1075 - n - ex, r > 0]
  end

  # --- C の uint64_t の演算 (D51)。firmware の Integer は 64bit の符号付きで、+ - * は桁あふれの罠があるので helper で

  # x >> n (論理 shift)。n は 0 以上
  # C: none (D51)
  def __fpga_u64_shr(x, n)
    return x if n == 0
    return 0 if n >= 64
    return __fpga_shr(x, n) if x >= 0
    __fpga_or(__fpga_shr(__fpga_and(x, 9223372036854775807), n), __fpga_shl(1, 63 - n))
  end

  # x < y (符号無しで)
  # C: none (D51)
  def __fpga_u64_lt(x, y)
    __fpga_xor(x, -9223372036854775807 - 1) < __fpga_xor(y, -9223372036854775807 - 1)
  end

  # x + y (2^64 で回る)
  # C: none (D51)
  def __fpga_u64_add(x, y)
    l = __fpga_and(x, 4294967295) + __fpga_and(y, 4294967295)
    h = __fpga_u64_shr(x, 32) + __fpga_u64_shr(y, 32) + __fpga_shr(l, 32)
    __fpga_or(__fpga_shl(h, 32), __fpga_and(l, 4294967295))
  end

  # x - y (2^64 で回る)
  # C: none (D51)
  def __fpga_u64_sub(x, y)
    return x if y == 0
    return __fpga_u64_add(x, y) if y == -9223372036854775807 - 1 # -2^63 は 2^64 で回すと自分
    __fpga_u64_add(x, 0 - y)
  end

  # 64bit × 64bit の 128bit の、上 (hi が真) か下の 64bit。22bit ずつの 3 桁で (fp_uscale.c の mul64 の移植用の形と同じ積)
  # C: src/fp_uscale.c mul64 (D51)
  def __fpga_mul64(a, b, hi)
    a0 = __fpga_and(a, 4194303)
    a1 = __fpga_and(__fpga_u64_shr(a, 22), 4194303)
    a2 = __fpga_u64_shr(a, 44)
    b0 = __fpga_and(b, 4194303)
    b1 = __fpga_and(__fpga_u64_shr(b, 22), 4194303)
    b2 = __fpga_u64_shr(b, 44)
    c0 = a0 * b0
    c1 = a0 * b1 + a1 * b0 + __fpga_shr(c0, 22)
    c2 = a0 * b2 + a1 * b1 + a2 * b0 + __fpga_shr(c1, 22)
    return __fpga_or(__fpga_or(__fpga_and(c0, 4194303), __fpga_shl(__fpga_and(c1, 4194303), 22)), __fpga_shl(c2, 44)) unless hi
    c3 = a1 * b2 + a2 * b1 + __fpga_shr(c2, 22)
    c4 = a2 * b2 + __fpga_shr(c3, 22)
    __fpga_or(__fpga_or(__fpga_shr(__fpga_and(c2, 4194303), 20), __fpga_shl(__fpga_and(c3, 4194303), 2)), __fpga_shl(c4, 24))
  end

  # --- src/fp_uscale.c (数と文字列の変換、Russ Cox の unrounded scaling)。uint64_t は上の helper で

  # C: src/fp_uscale.c log10_pow2
  def __fpga_log10_pow2(x)
    x * 78913 / 262144 # >> 18 (算術 shift は floor の割り算)
  end

  # C: src/fp_uscale.c log2_pow10
  def __fpga_log2_pow10(x)
    x * 108853 / 32768 # >> 15
  end

  # C: src/fp_uscale.c skewed
  def __fpga_skewed(e)
    (e * 631305 - 261663) / 2097152 # >> 21
  end

  # pow10_tab[p - POW10_MIN] の hi (lo が偽) か lo。表は __fpga_pow10_tab の irep の pool で、行ごとに 1 つの
  # 16 バイトの文字列 (big endian の hi と lo)。mrbc は並べた文字列の literal を行ごとの pool に置く
  # C: src/fp_uscale.c pow10_tab (D51)
  def __fpga_pow10_ent(p, lo)
    pr = __fpga_and(__fpga_search(__fpga_image(5), __fpga_addr(:__fpga_pow10_tab)), -4) # L:IMG_object_class 可視性の bit を除く
    ir = __fpga_ld32(pr + 8) # L:P_BODY
    a = __fpga_lo(__fpga_ldv(__fpga_ld32(ir + 12) + (p + 343) * 16)) + (lo ? 8 : 0) # L:I_POOL L:VALUE POW10_MIN
    __fpga_or(__fpga_shl(__fpga_ld32(a), 32), __fpga_ld32(a + 4))
  end

  # c は prescale の {pow10_tab[p - POW10_MIN], s}。p と s で渡す
  # C: src/fp_uscale.c uscale
  def __fpga_uscale(x, p, s)
    pmhi = __fpga_pow10_ent(p, false)
    hi = __fpga_mul64(x, pmhi, true)
    mid = __fpga_mul64(x, pmhi, false)
    sticky = 1
    return sticky if s >= 64
    mask = __fpga_u64_sub(__fpga_shl(1, s), 1)
    if __fpga_and(hi, mask) == 0
      mid2 = __fpga_mul64(x, __fpga_pow10_ent(p, true), true)
      sticky = __fpga_u64_lt(1, __fpga_u64_sub(mid, mid2)) ? 1 : 0
      hi = __fpga_u64_sub(hi, 1) if __fpga_u64_lt(mid, mid2)
    end
    __fpga_or(__fpga_u64_shr(hi, s), sticky)
  end

  # C: src/fp_uscale.c ur_floor
  def __fpga_ur_floor(u)
    __fpga_u64_shr(u, 2)
  end

  # C: src/fp_uscale.c ur_round
  def __fpga_ur_round(u)
    __fpga_u64_shr(__fpga_u64_add(u, 1 + __fpga_and(__fpga_u64_shr(u, 2), 1)), 2)
  end

  # C: src/fp_uscale.c ur_ceil
  def __fpga_ur_ceil(u)
    __fpga_u64_shr(__fpga_u64_add(u, 3), 2)
  end

  # unpack64 の *m (1.0 が 2^63 の 64bit に広げた仮数)
  # C: src/fp_uscale.c unpack64
  def __fpga_unpack64_m(f)
    m = __fpga_shl(__fpga_and(f, 4503599627370495), 11)
    return __fpga_or(m, -9223372036854775807 - 1) if __fpga_and(f, 9218868437227405312) > 0
    __fpga_shl(m, 64 - __fpga_bitlen(m)) # 非正規化数: clz64 だけ上げる
  end

  # unpack64 の *e
  # C: src/fp_uscale.c unpack64
  def __fpga_unpack64_e(f)
    exp = __fpga_shr(__fpga_and(f, 9223372036854775807), 52)
    return exp - 1 - 1085 if exp > 0 # min_exp = -(1074 + 11)
    -1085 - (64 - __fpga_bitlen(__fpga_shl(__fpga_and(f, 4503599627370495), 11)))
  end

  # C: src/fp_uscale.c pack64
  def __fpga_pack64(m, e)
    return m if __fpga_and(m, 4503599627370496) == 0 # 非正規化数
    biased = 1075 + e
    return 9218868437227405312 if biased >= 2047 # 無限大
    __fpga_or(__fpga_and(m, __fpga_xor(4503599627370496, -1)), __fpga_shl(biased, 52))
  end

  # 0 の数 (count_digits の uint64_pow10[n])
  # C: src/fp_uscale.c uint64_pow10
  def __fpga_uint64_pow10(n)
    v = 1
    while n > 0
      v *= 10
      n -= 1
    end
    v
  end

  # d (2^63 より小さい) の 10 進の桁の数
  # C: src/fp_uscale.c count_digits
  def __fpga_count_digits(d)
    return 1 if d == 0
    nd = __fpga_log10_pow2(__fpga_bitlen(d))
    nd + (d >= __fpga_uint64_pow10(nd) ? 1 : 0)
  end

  # x * 10^p の末尾の 0 を除く。[x, p] を返す
  # C: src/fp_uscale.c trim_zeros
  def __fpga_trim_zeros(x, p)
    d = __fpga_mul64(x, -3689348814741910323, false) # inv5
    d = __fpga_or(__fpga_u64_shr(d, 1), __fpga_shl(d, 63))
    return [x, p] unless d >= 0 && d <= 1844674407370955161 # UINT64_MAX / 10
    x = d
    p += 1
    d = __fpga_mul64(x, -4078282918271054303, false) # inv5p8
    d = __fpga_or(__fpga_u64_shr(d, 8), __fpga_shl(d, 56))
    if d >= 0 && d <= 184467440737 # UINT64_MAX / 100000000
      x = d
      p += 8
    end
    d = __fpga_mul64(x, -3276141747490816367, false) # inv5p4
    d = __fpga_or(__fpga_u64_shr(d, 4), __fpga_shl(d, 60))
    if d >= 0 && d <= 1844674407370955 # UINT64_MAX / 10000
      x = d
      p += 4
    end
    d = __fpga_mul64(x, -8116567392432202711, false) # inv5p2
    d = __fpga_or(__fpga_u64_shr(d, 2), __fpga_shl(d, 62))
    if d >= 0 && d <= 184467440737095516 # UINT64_MAX / 100
      x = d
      p += 2
    end
    d = __fpga_mul64(x, -3689348814741910323, false) # inv5
    d = __fpga_or(__fpga_u64_shr(d, 1), __fpga_shl(d, 63))
    if d >= 0 && d <= 1844674407370955161
      x = d
      p += 1
    end
    [x, p]
  end

  # 一番短い 10 進 d * 10^p。[d, p] を返す (d は 10^17 程度で 2^63 より小さい)
  # C: src/fp_uscale.c shortest
  def __fpga_shortest(f)
    min_exp = -1085 # FLO_MIN_EXP
    m = __fpga_unpack64_m(f)
    e = __fpga_unpack64_e(f)
    z = 11 # FLO_SHIFT
    if m == -9223372036854775807 - 1 && e > min_exp # 1ULL << 63
      p = 0 - __fpga_skewed(e + z)
      mn = __fpga_u64_sub(m, __fpga_shl(1, z - 2))
    else
      z = 11 + (min_exp - e) if e < min_exp
      p = 0 - __fpga_log10_pow2(e + z)
      mn = __fpga_u64_sub(m, __fpga_shl(1, z - 1))
    end
    mx = __fpga_u64_add(m, __fpga_shl(1, z - 1))
    odd = __fpga_and(__fpga_u64_shr(m, z), 1)
    lp = __fpga_log2_pow10(p)
    s = 0 - (e + lp + 3) # prescale
    dmin = __fpga_ur_ceil(__fpga_u64_add(__fpga_uscale(mn, p, s), odd))
    dmax = __fpga_ur_floor(__fpga_u64_sub(__fpga_uscale(mx, p, s), odd))
    d = dmax / 10
    return __fpga_trim_zeros(d, 0 - (p - 1)) if d * 10 >= dmin
    if dmin < dmax
      d = __fpga_ur_round(__fpga_uscale(m, p, s))
    else
      d = dmin
    end
    [d, 0 - p]
  end

  # C: src/fp_uscale.c parse_decimal
  def __fpga_parse_decimal(d, p)
    return 0 if d == 0
    b = d < 0 ? 64 : __fpga_bitlen(d) # bits_len64 (符号無し)
    lp = __fpga_log2_pow10(p)
    e = 53 - b - lp
    e = 1074 if e > 1074
    u = __fpga_uscale(__fpga_shl(d, 64 - b), p, 0 - (e - (64 - b) + lp + 3)) # prescale(e - (64 - b), p, lp)
    m = __fpga_ur_round(u)
    if m >= 9007199254740992 # 1ULL << 53
      u = __fpga_or(__fpga_u64_shr(u, 1), __fpga_and(u, 1))
      m = __fpga_ur_round(u)
      e -= 1
    end
    __fpga_pack64(m, 0 - e)
  end

  # buf から nd 桁の u (2^63 より小さい) を書く。i2a の表の 2 文字を割り算で同じに
  # C: src/fp_uscale.c format_base10
  def __fpga_format_base10(buf, nd, u)
    while nd >= 2
      nd -= 2
      idx = __fpga_rem(u, 100)
      u /= 100
      __fpga_st8(buf + nd, 48 + idx / 10)
      __fpga_st8(buf + nd + 1, 48 + __fpga_rem(idx, 10))
    end
    __fpga_st8(buf, 48 + u) if nd > 0
  end

  # 番地 s に指数を書き、書いたバイトの数を返す
  # C: src/fp_uscale.c emit_exp
  def __fpga_emit_exp(s, e_char, exp)
    __fpga_st8(s, e_char)
    if exp < 0
      __fpga_st8(s + 1, 45) # '-'
      exp = 0 - exp
    else
      __fpga_st8(s + 1, 43) # '+'
    end
    k = 2
    if exp >= 100
      __fpga_st8(s + k, 48 + exp / 100)
      exp = __fpga_rem(exp, 100)
      k += 1
    end
    __fpga_st8(s + k, 48 + exp / 10)
    __fpga_st8(s + k + 1, 48 + __fpga_rem(exp, 10))
    k + 2
  end

  # buf に書いた長さを返す。firmware が呼ぶのは mrb_float_to_str の 'g' と prec -2 (一番短い形) だけで、
  # 桁の数を決める 'e' 'f' 'g' (fixed_width) の道は写していない (止まる)
  # C: src/fp_uscale.c mrb_format_float
  def __fpga_format_float(f, buf, buf_size, fmt, prec, sign)
    s = buf
    buf_remaining = buf_size - 1
    alt_form = false
    if __fpga_and(fmt, 128) > 0
      fmt = __fpga_and(fmt, 127)
      alt_form = true
    end
    if buf_size <= 7 # FLT_MIN_BUF_SIZE
      if buf_size >= 2
        __fpga_st8(s, 63) # '?'
        s += 1
      end
      __fpga_st8(s, 0) if buf_size >= 1
      return buf_size >= 2 ? 1 : 0
    end
    if f < 0 # signbit
      __fpga_st8(s, 45) # '-'
      s += 1
      f = __fpga_and(f, 9223372036854775807) # f = -f
    elsif sign > 0
      __fpga_st8(s, sign)
      s += 1
    end
    buf_remaining -= s - buf
    uc = __fpga_and(fmt, 32)
    if __fpga_f64_inf_p(f)
      __fpga_st8(s, __fpga_xor(73, uc)) # 'I'
      __fpga_st8(s + 1, __fpga_xor(78, uc)) # 'N'
      __fpga_st8(s + 2, __fpga_xor(70, uc)) # 'F'
      __fpga_st8(s + 3, 0)
      return s + 3 - buf
    end
    if __fpga_f64_nan_p(f)
      __fpga_st8(s, __fpga_xor(78, uc)) # 'N'
      __fpga_st8(s + 1, __fpga_xor(65, uc)) # 'A'
      __fpga_st8(s + 2, __fpga_xor(78, uc)) # 'N'
      __fpga_st8(s + 3, 0)
      return s + 3 - buf
    end
    use_shortest = prec == -2
    prec = 6 if prec < 0
    e_char = __fpga_or(69, __fpga_and(fmt, 32)) # 'E'
    fmt = __fpga_or(fmt, 32)
    if fmt == 103 # 'g'
      if use_shortest
        fmt = 83 # 'S'
      elsif prec == 0
        prec = 1
      end
    end
    __fpga_halt unless fmt == 83 # 'e' 'f' 'g' の桁の数の道は写していない
    if f == 0
      __fpga_st8(s, 48) # '0' (g の 0。alt_form と prec > 1 の時の "." と 0 は 'S' に無い)
      s += 1
    else
      dp = __fpga_shortest(f)
      d = __fpga_aref(dp, 0)
      p = __fpga_aref(dp, 1)
      nd = __fpga_count_digits(d)
      exp = p + nd - 1
      digs = __fpga_temp_alloc(20) # char digs[17] (D84)
      __fpga_format_base10(digs, nd, d)
      if exp < -4 || exp >= 15
        __fpga_st8(s, __fpga_ld8(digs)) # e の形
        s += 1
        if nd > 1
          __fpga_st8(s, 46) # '.'
          __fpga_copy(s + 1, digs + 1, nd - 1)
          s += nd
        end
        s += __fpga_emit_exp(s, e_char, exp)
      elsif exp < 0 # f の形
        __fpga_st8(s, 48)
        __fpga_st8(s + 1, 46)
        s += 2
        i = 0
        while i < 0 - (exp + 1)
          __fpga_st8(s, 48)
          s += 1
          i += 1
        end
        __fpga_copy(s, digs, nd)
        s += nd
      else
        i = 0
        while i <= exp && i < nd
          __fpga_st8(s, __fpga_ld8(digs + i))
          s += 1
          i += 1
        end
        while i <= exp
          __fpga_st8(s, 48)
          s += 1
          i += 1
        end
        if nd > exp + 1
          __fpga_st8(s, 46)
          s += 1
          while i < nd
            __fpga_st8(s, __fpga_ld8(digs + i))
            s += 1
            i += 1
          end
        end
      end
    end
    __fpga_st8(s, 0)
    s - buf
  end

  # 文字列 (NUL で終わる) の番地から読む。[読めたか, 読み終えた番地, double のビット] を返す
  # C: src/fp_uscale.c mrb_read_float
  def __fpga_read_float(str)
    p = str
    a = p
    d = 0
    nd = 0
    dp = 0
    trunc = 0
    sign = 1
    any_digits = false
    p += 1 while __fpga_isspace(__fpga_ld8(p))
    if __fpga_ld8(p) == 45 # '-'
      sign = -1
      p += 1
    elsif __fpga_ld8(p) == 43 # '+'
      p += 1
    end
    while __fpga_ld8(p) == 48 # 先頭の 0
      p += 1
      any_digits = true
    end
    while __fpga_isdigit(__fpga_ld8(p)) # 整数の所
      if nd < 19
        d = __fpga_u64_add(__fpga_mul64(d, 10, false), __fpga_ld8(p) - 48)
        nd += 1
      elsif trunc < 100000
        trunc += 1
      end
      any_digits = true
      p += 1
      a = p
    end
    if __fpga_ld8(p) == 46 # '.' 小数の所
      p += 1
      if nd == 0
        while __fpga_ld8(p) == 48
          dp += 1
          p += 1
          any_digits = true
        end
      end
      while __fpga_isdigit(__fpga_ld8(p))
        if nd < 19
          d = __fpga_u64_add(__fpga_mul64(d, 10, false), __fpga_ld8(p) - 48)
          nd += 1
          dp += 1
        end
        any_digits = true
        p += 1
      end
      a = p
    end
    return [false, str, 0] unless any_digits
    final_p = trunc - dp
    if __fpga_or(__fpga_ld8(p), 32) == 101 # 'e'
      e = 0
      exp_sign = 1
      p += 1
      if __fpga_ld8(p) == 45
        exp_sign = -1
        p += 1
      elsif __fpga_ld8(p) == 43
        p += 1
      end
      if __fpga_isdigit(__fpga_ld8(p))
        while __fpga_isdigit(__fpga_ld8(p))
          e = e * 10 + (__fpga_ld8(p) - 48) if e < 10000
          p += 1
        end
        final_p += e * exp_sign
        a = p
      end
    end
    if d == 0
      res = 0
    elsif final_p > 308
      res = 9218868437227405312 # HUGE_VAL
    elsif final_p < -343 # POW10_MIN
      res = 0
    else
      res = __fpga_parse_decimal(d, final_p)
    end
    res = __fpga_or(res, -9223372036854775807 - 1) if sign < 0 # -res
    [true, a, res]
  end

  # C: include/mruby.h ISSPACE
  def __fpga_isspace(c)
    c == 32 || (c >= 9 && c <= 13)
  end

  # C: include/mruby.h ISDIGIT
  def __fpga_isdigit(c)
    c >= 48 && c <= 57
  end

