  # mrb_float_value: NaN は作るたびに通し番号を中身に入れる (boxing_no.h の SET_FLOAT_VALUE)
  # C: include/mruby/boxing_no.h SET_FLOAT_VALUE
  def __fpga_float_value(f)
    f = __fpga_nan_serialize(f, __fpga_nan_serial_next) if __fpga_f64_nan_p(f)
    __fpga_mkval(5, f) # L:TAG_FLOAT
  end

  # C: include/mruby/value.h mrb_nan_serialize
  def __fpga_nan_serialize(f, n)
    f = __fpga_and(f, __fpga_xor(2251799813685247, -1)) # ~MRB_NAN_SERIAL_MAX
    __fpga_or(__fpga_or(f, 2251799813685248), __fpga_and(n, 2251799813685247)) # MRB_NAN_QUIET_BIT
  end

  # mrb->nan_serial++ (uint64_t を 2 語で)
  # C: src/etc.c mrb_nan_serial_next
  def __fpga_nan_serial_next
    hi = __fpga_ld32(1093 * 4) # L:IMG_nan_serial L:WORD
    lo = __fpga_ld32(1094 * 4) # L:IMG_nan_serial_lo L:WORD
    n = __fpga_or(__fpga_shl(hi, 32), lo)
    lo += 1
    if lo == 4294967296
      lo = 0
      __fpga_st32(1093 * 4, __fpga_and(hi + 1, 4294967295)) # L:IMG_nan_serial L:WORD
    end
    __fpga_st32(1094 * 4, lo) # L:IMG_nan_serial_lo L:WORD
    n
  end

