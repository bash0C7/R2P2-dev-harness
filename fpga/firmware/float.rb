    return __fpga_f64_div(x, y) if (__fpga_f64_cmp(y, 0) == 0) == false
    return 9221120237041090560 if __fpga_f64_cmp(x, 0) == 0 # NAN
    __fpga_f64_mul(__fpga_f64_mul(x, y < 0 ? -4616189618054758400 : 4607182418800017408), 9218868437227405312) # x * (signbit(y) ? -1.0 : 1.0) * INFINITY
  end

  # 整数と Float を丸めずに比べる: 1、0、-1、y が NaN なら -2
  # C: src/numeric.c mrb_int_float_cmp
  def __fpga_int_float_cmp(x, y)
    return -2 if __fpga_f64_nan_p(y)
    return 1 if __fpga_f64_cmp(y, -4332462841530417152) < 0 # (mrb_float)MRB_INT_MIN
    return -1 if __fpga_f64_cmp(y, 4890909195324358656) >= 0 # -(mrb_float)MRB_INT_MIN
    yi = __fpga_f64_to_int(y)
    return 1 if x > yi
    return -1 if x < yi
    c = __fpga_f64_cmp(y, __fpga_f64_from_int(yi))
    return -1 if c > 0
    return 1 if c < 0
    0
  end

  # 比べる: 1、0、-1、比べられなければ -2、NaN との組は -3 (CMP_UNORDERED)
  # C: src/numeric.c cmpnum
  def __fpga_cmpnum(v1, v2)
    t1 = __fpga_tag(v1)
    t2 = __fpga_tag(v2)
    if t1 == 3 && t2 == 5 # L:TAG_INT L:TAG_FLOAT
      c = __fpga_int_float_cmp(v1, __fpga_int(v2)) # cmpnum_int_float
      return c == -2 ? -3 : c
    end
    if t1 == 5 && t2 == 3 # L:TAG_FLOAT L:TAG_INT
      c = __fpga_int_float_cmp(v2, __fpga_int(v1))
      return -3 if c == -2
      return 0 - c # cmpnum_rev
    end
    if t1 == 3 # L:TAG_INT
      if t2 == 3 # L:TAG_INT
        return 1 if v1 > v2
        return -1 if v1 < v2
        return 0
      end
      x = __fpga_f64_from_int(v1)
    else
      x = __fpga_as_float(v1)
    end
    if t2 == 5 # L:TAG_FLOAT
      y = __fpga_int(v2)
    else
      return -2 unless __fpga_kind_of(v2, Numeric)
      v = v2 <=> v1
      return -2 unless __fpga_tag(v) == 3 # L:TAG_INT mrb_fixnum_p
      return 0 - v
    end
    c = __fpga_f64_cmp(x, y)
    return -3 if c == 2 # NaN
    c
  end

  # C: src/numeric.c cmpnum_total
  def __fpga_cmpnum_total(v1, v2)
    n = __fpga_cmpnum(v1, v2)
    n == -3 ? -2 : n
  end

  # [div, mod] のビットを返す (C は divp と modp に書く)。want_div は divp と modp の両方がある時
  # C: src/numeric.c flodivmod
  def __fpga_flodivmod(x, y, want_div)
    if __fpga_f64_nan_p(y)
      div = y
      mod = y
    else
      __fpga_raise(ZeroDivisionError, "divided by 0") if __fpga_f64_cmp(y, 0) == 0 # mrb_int_zerodiv
      if __fpga_f64_inf_p(y) && __fpga_f64_inf_p(x) == false
        mod = x
      else
        mod = __fpga_f64_fmod(x, y)
      end
      if __fpga_f64_inf_p(x) && __fpga_f64_inf_p(y) == false
        div = x
      else
        div = __fpga_f64_div(__fpga_f64_sub(x, mod), y)
        div = __fpga_f64_round(div) if want_div
      end
      div = 0 if __fpga_f64_cmp(div, 0) == 0 # -0.0 を 0.0 に
      mod = 0 if __fpga_f64_cmp(mod, 0) == 0
      if __fpga_f64_cmp(__fpga_f64_mul(y, mod), 0) < 0
        mod = __fpga_f64_add(mod, y)
        div = __fpga_f64_sub(div, 4607182418800017408) # 1.0
      end
    end
    [div, mod]
  end

  # (mrb_int)f を Integer に。あふれは RangeError
  # C: src/numeric.c flo_rounding_int
  def __fpga_flo_rounding_int(f)
