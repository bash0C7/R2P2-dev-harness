        number = __fpga_f64_sub(d, __fpga_f64_cmp(__fpga_f64_sub(d, number), 4602678819172646912) >= 0 ? 4607182418800017408 : 0)
      end
      number = ndigits < 0 ? __fpga_f64_mul(number, f) : __fpga_f64_div(number, f)
    end
    if ndigits > 0
      return self if __fpga_f64_nan_p(number) || __fpga_f64_inf_p(number) # !isfinite
      return __fpga_float_value(number)
    end
    return __fpga_float_value(number) unless __fpga_fixable_float(number)
