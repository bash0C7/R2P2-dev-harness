  # floor と ceil (func は floor か ceil の helper の名前)。args は mrb_get_args の "|i"
  # C: src/numeric.c flo_rounding
  def __fpga_flo_rounding(num, args, ceil)
    f = __fpga_int(num)
    ndigits = __fpga_alen(args) > 0 ? __fpga_as_int(__fpga_aref(args, 0)) : 0
    fprec = 15
    if __fpga_f64_cmp(f, 0) == 0
      return ndigits > 0 ? __fpga_float_value(f) : 0
    end
    if ndigits > 0
      return num if ndigits > fprec
      d = __fpga_f64_pow(4621819117588971520, __fpga_f64_from_int(ndigits)) # pow(10, ndigits)
      f = __fpga_f64_mul(f, d)
      f = ceil ? __fpga_f64_ceil(f) : __fpga_f64_floor(f)
      f = __fpga_f64_div(f, d)
      __fpga_check_num_exact(f)
      return __fpga_float_value(f)
    end
    if ndigits < 0
      d = __fpga_f64_pow(4621819117588971520, __fpga_f64_from_int(0 - ndigits))
      f = __fpga_f64_div(f, d)
      f = ceil ? __fpga_f64_ceil(f) : __fpga_f64_floor(f)
      f = __fpga_f64_mul(f, d)
    else
      f = ceil ? __fpga_f64_ceil(f) : __fpga_f64_floor(f)
    end
    __fpga_check_num_exact(f)
    __fpga_flo_rounding_int(f)
  end

  # C: src/numeric.c mrb_float_to_str
  def __fpga_float_to_str(flo)
    buf = __fpga_temp_alloc(25) # char buf[25] (D84)
    n = __fpga_format_float(__fpga_int(flo), buf, 25, 103, -2, 0) # 'g'
    p = buf
    while p < buf + n
      return __fpga_str_new(buf, n) if __fpga_ld8(p) == 46 # '.'
      if __fpga_ld8(p) == 101 # 'e': 前に ".0" を入れる
        __fpga_move(p + 2, p, buf + n - p)
        __fpga_st8(p, 46)
        __fpga_st8(p + 1, 48)
        return __fpga_str_new(buf, n + 2)
      end
      p += 1
    end
    __fpga_st8(p, 46) # ".0"
    __fpga_st8(p + 1, 48)
    __fpga_str_new(buf, n + 2)
  end

  # FNV-1a (8 バイトの値を、host (little endian) の記憶の並びで)
  # C: src/string.c mrb_byte_hash_step
  def __fpga_byte_hash8(v)
    hval = 2166136261 # FNV1_32_INIT
    i = 0
    while i < 8
      hval = __fpga_xor(hval, __fpga_and(__fpga_u64_shr(v, i * 8), 255))
      hval = __fpga_and(hval * 16777619, 4294967295) # FNV_32_PRIME (mod 2^32)
      i += 1
    end
    hval
  end

