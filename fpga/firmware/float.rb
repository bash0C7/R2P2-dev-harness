    __fpga_byte_hash8(f)
  end

  # C: src/string.c mrb_str_len_to_dbl
  def __fpga_str_len_to_dbl(s, len, badcheck)
    __fpga_halt if badcheck # badcheck の道 (Kernel#Float、mruby-kernel-ext) は写していない
    p = s
    pend = p + len
    buf = __fpga_temp_alloc(80) # char buf[DBL_DIG * 4 + 20] (D84)
    prev = 0
    dot = false
    p += 1 while p < pend && __fpga_isspace(__fpga_ld8(p))
    p2 = p
    if pend - p > 2 && __fpga_ld8(p) == 48 && (__fpga_ld8(p + 1) == 120 || __fpga_ld8(p + 1) == 88) # "0x"
      return 0
    end
    nocopy = false
    while p < pend
      if __fpga_ld8(p) == 0
        pend = p
        p = p2
        nocopy = true
        break
      end
      if badcheck == false && __fpga_ld8(p) == 32
        pend = p
        p = p2
        nocopy = true
        break
      end
      break if __fpga_ld8(p) == 95 # '_'
      p += 1
    end
    unless nocopy
      p = p2
      n = buf
      while p < pend
        c = __fpga_ld8(p)
        p += 1
        dot = true if c == 46
        if c == 95 # '_' 数字の間の _ を除く
          break if n == buf || __fpga_isdigit(prev) == false || p == pend
        else
          if n == buf + 79 # buffer overflow
            break if dot # 小数の残りを切る
            return 9218868437227405312 # INFINITY
          end
          __fpga_st8(n, c)
          n += 1
        end
        prev = c
      end
      __fpga_st8(n, 0)
      p = buf
    end
    r = __fpga_read_float(p)
    return 0 unless __fpga_aref(r, 0)
    __fpga_aref(r, 2)
  end
