    __fpga_check_num_exact(number)
    f = 4607182418800017408 # 1.0
    return 0 if ndigits < -17 # -DBL_DIG-2
    i = ndigits >= 0 ? ndigits : 0 - ndigits
    return self if ndigits > 17 # DBL_DIG+2
    while i > 0 # while (--i >= 0)
      f = __fpga_f64_mul(f, 4621819117588971520) # 10.0
      i -= 1
    end
    if __fpga_f64_inf_p(f)
      number = 0 if ndigits < 0
    else
      number = ndigits < 0 ? __fpga_f64_div(number, f) : __fpga_f64_mul(number, f)
      if __fpga_f64_cmp(number, 0) > 0 # round(3) の家で作った形
        d = __fpga_f64_floor(number)
        number = __fpga_f64_add(d, __fpga_f64_cmp(__fpga_f64_sub(number, d), 4602678819172646912) >= 0 ? 4607182418800017408 : 0) # 0.5
      elsif __fpga_f64_cmp(number, 0) < 0
